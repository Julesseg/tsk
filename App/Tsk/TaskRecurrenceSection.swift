import SwiftUI
import TskCore

struct TaskRecurrenceSection: View {
    let task: TaskRecord
    let store: TaskStore

    var body: some View {
        if let recurrence = task.recurrenceInspection {
            Section(title(recurrence.kind)) {
                if let rule = recurrence.rule { LabeledContent("Recurrence rule", value: rule).accessibilityIdentifier("recurrence-rule-value") }
                if let date = recurrence.firstDue { LabeledContent(recurrence.kind == .template ? "First due" : "Occurrence due", value: date.formatted(date: .abbreviated, time: .shortened)) }
                if recurrence.kind == .template {
                    Text("Occurrences are generated by your designated Taskwarrior client after it synchronizes and runs a report. Synchronize again to receive them here.").accessibilityIdentifier("external-generation-explanation")
                    if task.attributes["until"] != nil { Text("Taskwarrior 3.5 can generate the first occurrence beyond the Until date. Review the generator's result before relying on a precise series end.").font(.footnote) }
                    LabeledContent("Generated positions", value: String(recurrence.mask?.count ?? 0))
                } else if recurrence.kind == .occurrence {
                    if let id = recurrence.parentID {
                        if let template = store.allTasks.first(where: { $0.id == id }) {
                            NavigationLink("View recurring template") { TaskDetailView(store: store, task: template) }.accessibilityIdentifier("occurrence-template")
                        } else { Text("The linked template has not arrived in this saved dataset.") }
                    }
                    Text(task.status == "completed" ? "This completed occurrence remains in the series history." : "Edits and completion apply only to this occurrence. Other occurrences and the template remain unchanged.").accessibilityIdentifier("occurrence-only-explanation")
                }
                ForEach(recurrence.issues, id: \.self) { Text($0).foregroundStyle(.orange) }
            }
        }
    }

    private func title(_ kind: TaskRecurrenceInspection.Kind) -> String {
        switch kind { case .template: "Recurring template"; case .occurrence: "Generated occurrence"; case .unrecognized: "Recurrence data" }
    }
}
