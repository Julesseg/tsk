@Test(.enabled(if: ProcessInfo.processInfo.environment["TSK_TASKWARRIOR_BINARY"] != nil))
func nativePlanningPersistsIndependentTaskwarriorDatesAndTodayActions() async throws {
    let binary = try #require(ProcessInfo.processInfo.environment["TSK_TASKWARRIOR_BINARY"])
    let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
    try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
    defer { try? FileManager.default.removeItem(at: directory) }
    var calendar = Calendar(identifier: .gregorian)
    calendar.timeZone = TimeZone(identifier: "Europe/Paris")!
    let manager = TaskManager(replica: TaskChampionReplica(directory: directory), now: { Date(timeIntervalSince1970: 1791972000) }, calendar: calendar)
    var draft = TaskDraft(description: "Native planned task", attributes: ["due": "1792101600", "start": "1791928900", "opaque": "retain"])
    draft.setScheduled(TaskScheduledDate(date: Date(timeIntervalSince1970: 1791928800), hasTime: true))
    let original = try await manager.create(draft)
    #expect(try await manager.tasks(query: .today).map(\.id) == [original.id])
    let config = directory.appendingPathComponent("taskrc")
    try "data.location=\(directory.path)\nuda.opaque.type=string\nuda.tsk_scheduled_precision.type=string\nuda.tsk_completion_page.type=string\nuda.tsk_planner_order.type=string\nconfirmation=no\n".write(to: config, atomically: true, encoding: .utf8)
    let first = try exportedPlanningTask(binary: binary, config: config)
    #expect(first["scheduled"] as? String == "20261013T220000Z")
    #expect(first["due"] as? String == "20261015T220000Z")
    #expect(first["start"] as? String == "20261013T220140Z")
    var row = TaskRowDraft(task: original)
    row.taskDraft.setScheduled(TaskScheduledDate(date: Date(timeIntervalSince1970: 1792015200), hasTime: true))
    _ = try await manager.updateRow(row)
    let reopened = TaskManager(replica: TaskChampionReplica(directory: directory), now: { Date(timeIntervalSince1970: 1791972000) }, calendar: calendar)
    let edited = try await reopened.task(id: original.id)
    #expect(edited.scheduled(calendar: calendar)?.hasTime == true)
    #expect(edited.plannedDate == Date(timeIntervalSince1970: 1792015200))
    var untimed = TaskRowDraft(task: edited)
    untimed.taskDraft.setScheduled(TaskScheduledDate(date: edited.plannedDate!, hasTime: false))
    _ = try await reopened.updateRow(untimed)
    let untimedReopen = TaskManager(replica: TaskChampionReplica(directory: directory), calendar: calendar)
    #expect(try await untimedReopen.task(id: edited.id).scheduled(calendar: calendar)?.hasTime == false)
    #expect(edited.attributes["due"] == "1792101600")
    #expect(edited.attributes["start"] == "1791928900")
    #expect(edited.attributes["opaque"] == "retain")
    #expect(try await reopened.tasks(query: .today).isEmpty)
    _ = try await reopened.update(id: original.id, changes: ["due": "1791928800"])
    #expect(try await reopened.tasks(query: .today).isEmpty)
    #expect(try await reopened.dayPage(on: Date(timeIntervalSince1970: 1792015200)).map(\.id) == [original.id])
    let changed = try exportedPlanningTask(binary: binary, config: config)
    #expect(changed["scheduled"] as? String == "20261014T220000Z")
    #expect(changed["due"] as? String == "20261013T220000Z")
    #expect((changed["uuid"] as? String)?.lowercased() == original.id.uuidString.lowercased())
    _ = try await reopened.complete(id: original.id)
    #expect(try await reopened.tasks(query: .today).isEmpty)
    let completed = try exportedPlanningTask(binary: binary, config: config)
    #expect(completed["scheduled"] as? String == "20261014T220000Z")
    #expect(completed["due"] as? String == "20261013T220000Z")
    #expect(completed["status"] as? String == "completed")
    #expect(completed["opaque"] as? String == "retain")
    let history = TaskManager(replica: TaskChampionReplica(directory: directory), now: { Date(timeIntervalSince1970: 1792576800) }, calendar: calendar)
    let earlyHistory = try await history.dayPage(on: Date(timeIntervalSince1970: 1792015200))
    #expect(earlyHistory.map(\.id) == [original.id])
    #expect(earlyHistory.first?.status == "completed")
    var orderedDraft = TaskDraft(description: "First ordered task", attributes: ["project": "Order", "opaque": "retain order", "due": "1792101600"])
    orderedDraft.setScheduled(TaskScheduledDate(date: Date(timeIntervalSince1970: 1791928800), hasTime: false))
    let firstOrdered = try await manager.create(orderedDraft)
    let external = TaskChampionReplica(directory: directory)
    _ = try await external.update(id: firstOrdered.id, changes: ["tsk_planner_order": nil])
    orderedDraft.description = "Second ordered task"
    let secondOrdered = try await manager.create(orderedDraft)
    let before = try await manager.dayPage(on: Date(timeIntervalSince1970: 1791972000))
    #expect(before.map(\.id) == [firstOrdered.id, secondOrdered.id])
    var drag = try TaskDragSession(tasks: before, ids: [before[1].id], context: .day(Date(timeIntervalSince1970: 1791972000)), calendar: calendar)
    drag.cross(before[0].id)
    _ = try await manager.drop(drag)
    let fresh = TaskManager(replica: TaskChampionReplica(directory: directory), now: { Date(timeIntervalSince1970: 1791972000) }, calendar: calendar)
    #expect(try await fresh.dayPage(on: Date(timeIntervalSince1970: 1791972000)).map(\.id) == [before[1].id, before[0].id])
    let project = try await fresh.tasks(query: .unfinished, project: .project("Order"))
    drag = try TaskDragSession(tasks: project, ids: [project[1].id], context: .project("Order"), calendar: calendar)
    drag.cross(project[0].id)
    _ = try await fresh.drop(drag)
    _ = try await fresh.complete(ids: [before[0].id])
    let historyReopen = TaskManager(replica: TaskChampionReplica(directory: directory), now: { Date(timeIntervalSince1970: 1791972000) }, calendar: calendar)
    let retained = try await historyReopen.dayPage(on: Date(timeIntervalSince1970: 1791972000))
    #expect(retained.map(\.id) == [before[1].id, before[0].id])
    #expect(retained.last?.status == "completed")
    let relaunch = TaskManager(replica: TaskChampionReplica(directory: directory), calendar: calendar)
    #expect(try await relaunch.tasks(query: .unfinished, project: .project("Order")).map(\.id) == [before[1].id])
    for record in try await relaunch.tasks(query: .unfinished, project: .project("Order")) {
        #expect(record.scheduled(calendar: calendar) == orderedDraft.scheduled(calendar: calendar))
        #expect(record.attributes["opaque"] == "retain order")
        #expect(record.attributes["due"] == "1792101600")
    }
    var capture = TaskRowDraft(capturing: .day(Date(timeIntervalSince1970: 1791928800)), calendar: calendar)
    capture.taskDraft.description = "Captured after existing work"
    let captured = try await manager.create(capture.creationDraft(at: Date(timeIntervalSince1970: 1791972000)))
    let incoming = try await manager.create(TaskDraft(description: "Editor incoming", attributes: ["due": "1792101600", "opaque": "keep editor"]))
    var editedRow = TaskRowDraft(task: incoming)
    editedRow.taskDraft.setScheduled(.init(date: Date(timeIntervalSince1970: 1791928800), hasTime: false))
    _ = try await manager.updateRow(editedRow)
    let appended = TaskManager(replica: TaskChampionReplica(directory: directory), now: { Date(timeIntervalSince1970: 1791972000) }, calendar: calendar)
    #expect(try await appended.dayPage(on: Date(timeIntervalSince1970: 1791972000)).map(\.id) == [secondOrdered.id, firstOrdered.id, captured.id, incoming.id])
    _ = try await appended.update(id: incoming.id, changes: ["scheduled": "1792015200", "tsk_scheduled_precision": "v1:1792015200:timed"])
    _ = try await appended.applySelection(ids: [incoming.id], changes: .init(scheduled: .day(Date(timeIntervalSince1970: 1792101600))))
    let precisionReopen = TaskManager(replica: TaskChampionReplica(directory: directory), calendar: calendar)
    let persisted = try await precisionReopen.task(id: incoming.id)
    #expect(persisted.scheduled(calendar: calendar) == .init(date: Date(timeIntervalSince1970: 1792101600), hasTime: true))
    #expect(persisted.attributes["due"] == "1792101600")
    #expect(persisted.attributes["opaque"] == "keep editor")
    let exported = try exportedPlanningTask(binary: binary, config: config, id: incoming.id)
    #expect(exported["scheduled"] as? String == "20261015T220000Z")
    #expect(exported["tsk_scheduled_precision"] as? String == "v1:1792101600:timed")
    #expect(exported["tsk_planner_order"] as? String == persisted.attributes["tsk_planner_order"])
    #expect(exported["opaque"] as? String == "keep editor")
    let cliEdit = Process()
    cliEdit.executableURL = URL(fileURLWithPath: binary)
    cliEdit.arguments = ["rc:\(config.path)", "rc.recurrence=off", incoming.id.uuidString.lowercased(), "modify", "description:Edited by Taskwarrior"]
    cliEdit.standardOutput = FileHandle.nullDevice
    cliEdit.standardError = FileHandle.nullDevice
    try cliEdit.run()
    cliEdit.waitUntilExit()
    #expect(cliEdit.terminationStatus == 0)
    let returned = try await precisionReopen.task(id: incoming.id)
    #expect(returned.description == "Edited by Taskwarrior")
    #expect(returned.scheduled(calendar: calendar) == persisted.scheduled(calendar: calendar))
    #expect(returned.attributes["tsk_planner_order"] == persisted.attributes["tsk_planner_order"])
    #expect(returned.deadline == persisted.deadline && returned.attributes["opaque"] == "keep editor")

}

private func exportedPlanningTask(binary: String, config: URL, id: UUID? = nil) throws -> [String: Any] {
    let process = Process()
    process.executableURL = URL(fileURLWithPath: binary)
    process.arguments = ["rc:\(config.path)", "rc.recurrence=off", "export"]
    let output = Pipe()
    process.standardOutput = output
    process.standardError = FileHandle.nullDevice
    try process.run()
    let bytes = output.fileHandleForReading.readDataToEndOfFile()
    process.waitUntilExit()
    #expect(process.terminationStatus == 0)
    let records = try #require(JSONSerialization.jsonObject(with: bytes) as? [[String: Any]])
    if let id {
        let matching = records.first { ($0["uuid"] as? String)?.lowercased() == id.uuidString.lowercased() }
        return try #require(matching)
    }
    return try #require(records.first)
}

@Test func reopeningAnOrdinaryTaskPersistsItsOriginalDatesWithoutCompletionMetadata() async throws {
    let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
    defer { try? FileManager.default.removeItem(at: directory) }
    let manager = TaskChampionSession.makeManager(directory: directory)
    let original = try await manager.create(TaskDraft(description: "Complete and reopen", attributes: ["scheduled": "1792170900", "due": "1792257300", "opaque": "retain"]))
    _ = try await manager.complete(id: original.id)
    _ = try await manager.reopen(id: original.id)
    let reader = TaskChampionSession.makeManager(directory: directory)
    let saved = try await reader.task(id: original.id)
    #expect(saved.status == "pending")
    #expect(saved.attributes["end"] == nil && saved.attributes["tsk_completion_page"] == nil)
    #expect(saved.plannedDate == original.plannedDate && saved.deadline == original.deadline)
    #expect(saved.attributes["opaque"] == "retain")
}
